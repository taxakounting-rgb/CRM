from playwright.sync_api import sync_playwright
URL='http://localhost:4173/'; errs=[]
def ok(n,c): print(('PASS ' if c else 'FAIL ')+n)
def watch(pg,t): pg.on('pageerror',lambda e:errs.append(t+':'+str(e)))
with sync_playwright() as p:
    b=p.chromium.launch()
    A=b.new_context(); a=A.new_page(); watch(a,'A')
    a.goto(URL); a.wait_for_selector('[data-gate=signup]')
    ok('First screen: company Sign up + Sign in', a.locator('[data-gate=signin]').count()==1)
    a.screenshot(path='/tmp/g1.png')
    a.click('[data-gate=signup]'); a.wait_for_selector('#co-form')
    a.fill('[name=name]','Acme Solutions'); a.fill('[name=id]','acme-co'); a.fill('[name=password]','Compass123'); a.fill('[name=confirm]','Compass123')
    a.click('#co-form button[type=submit]'); a.wait_for_selector('#su-form')
    ok('Wizard opens with company name prefilled', a.input_value('[name=name]')=='Acme Solutions')
    for _ in range(3): a.click('#su-form button[type=submit]'); a.wait_for_timeout(250)
    a.fill('[name=admName]','Owner One'); a.fill('[name=admUser]','owner1'); a.fill('[name=password]','Secret123'); a.fill('[name=confirm]','Secret123')
    a.click('#su-form button[type=submit]'); a.wait_for_timeout(1800)
    ok('Admin created and inside the app', a.locator('#main').count()>0)
    # add an employee (second login inside company)
    a.evaluate("""(async()=>{const u={id:'u_emp',username:'sara',name:'Sara',email:'',roleId:'role_staff',status:'active',mustChange:false,createdAt:new Date().toISOString()};await Auth.setPassword(u,'Sara12345');Store.commit(s=>{s.users.push(u)});})()"""); a.wait_for_timeout(3000)
    ok('Pushed to cloud', a.evaluate("Cloud.st.ver>=2"))
    a.evaluate("Auth.logout()"); a.wait_for_timeout(500)
    ok('After logout: employee login (not company gate)', a.locator('#login-form').count()==1)
    a.screenshot(path='/tmp/g2.png')
    # Computer B
    B=b.new_context(); c=B.new_page(); watch(c,'B')
    c.goto(URL); c.wait_for_selector('[data-gate=signin]'); c.click('[data-gate=signin]'); c.wait_for_selector('#col-form')
    c.fill('[name=id]','acme-co'); c.fill('[name=password]','Wrong999'); c.click('#col-form button[type=submit]'); c.wait_for_timeout(1000)
    ok('B: wrong company password rejected', c.locator('[data-e]').inner_text().strip()!='')
    c.fill('[name=password]','Compass123'); c.click('#col-form button[type=submit]'); c.wait_for_selector('#login-form')
    ok('B: company sign in -> employee login screen', True)
    c.fill('[name=username]','sara'); c.fill('[name=password]','Sara12345'); c.click('#login-form button[type=submit]'); c.wait_for_timeout(1500)
    ok('B: employee Sara logged in on another computer', c.locator('#main').count()>0 and c.evaluate("Auth.user.username")=='sara')
    ok('B: company data from cloud', c.evaluate("Store.s.settings.company.name")=='Acme Solutions')
    # reload B: still company-signed-in, goes to employee login/resume
    c.reload(); c.wait_for_timeout(1500)
    ok('B: after reload no company password needed', c.locator('#main').count()>0 or c.locator('#login-form').count()>0)
    # Computer C: different company is isolated
    C=b.new_context(); d=C.new_page(); watch(d,'C'); d.goto(URL); d.click('[data-gate=signup]'); d.wait_for_selector('#co-form')
    d.fill('[name=name]','Other Ltd'); d.fill('[name=id]','acme-co'); d.fill('[name=password]','Compass123'); d.fill('[name=confirm]','Compass123'); d.click('#co-form button[type=submit]'); d.wait_for_timeout(1200)
    ok('C: duplicate company username blocked', d.locator('#co-form').count()==1)
    ok('Backup/restore UI gone', a.evaluate("document.body.innerHTML.includes('Restore from backup')")==False)
    # settings page has no backup export
    a.goto(URL); a.wait_for_selector('#login-form'); a.fill('[name=username]','owner1'); a.fill('[name=password]','Secret123'); a.click('#login-form button[type=submit]'); a.wait_for_timeout(1200)
    a.goto(URL+'#/settings/backup'); a.wait_for_timeout(800)
    t=a.inner_text('#main'); ok('Settings: no backup file / restore upload', 'Export full backup' not in t and 'Restore' not in t.replace('Restore data','') or 'Backup file' not in t)
    a.screenshot(path='/tmp/g3.png')
    b.close()
print('ERRORS:',errs if errs else 'none')
